def build(root):
    out = os.path.join(root, "wikidocs")
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    files = []

    def write(rel, text, depth, title):
        path = os.path.join(out, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        files.append((depth, title, rel))

    write("00_머리말.md", PREFACE, 0, "머리말 — 이 책을 쓰는 방법")
    write("01_부모가이드/00_부모가이드.md", "# 부모 가이드\n\n수업을 시작하기 전에 한 번 읽어 주세요.\n\n"
          + "\n".join(f"- {t}" for t, _ in GUIDE) + "\n", 0, "부모 가이드")
    for i, (title, text) in enumerate(GUIDE, 1):
        write(f"01_부모가이드/{i:02d}_{title.replace(' ', '_').replace(',', '')}.md", text, 1, title)

    units = C.UNITS
    for n, (ptitle, pdesc) in PARTS.items():
        folder = f"{n + 10}_{ptitle.replace(' ', '_')}"
        us = [u for u in units if u["stage"] == n]
        intro = f"# {ptitle}\n\n{pdesc}\n\n| 단원 | 제목 |\n|:---:|---|\n" + "\n".join(f"| {u['unit']} | {u['title']} |" for u in us) + "\n"
        write(f"{folder}/00_{ptitle.replace(' ', '_')}.md", intro, 0, ptitle)
        for u in us:
            i = units.index(u)
            prev_u = units[i - 1] if i > 0 else None
            next_u = units[i + 1] if i + 1 < len(units) else None
            safe = u["title"].replace(" ", "_").replace("·", "").replace(",", "").replace("+", "").replace("=", "").replace("(", "").replace(")", "")
            safe = "_".join(x for x in safe.split("_") if x)
            a, b = u["unit"].split("-")
            write(f"{folder}/{a}-{int(b):02d}_{safe}.md", render_unit(u, prev_u, next_u), 1, f"{u['unit']} {u['title']}")

    write("20_부록/00_부록.md", "# 부록\n\n- 전체 낱말 목록\n- 진도 체크표\n- 출력용 활동지 만들기\n", 0, "부록")
    write("20_부록/01_전체_낱말_목록.md", appendix_words(), 1, "부록 1 — 전체 낱말 목록")
    write("20_부록/02_진도_체크표.md", appendix_progress(), 1, "부록 2 — 진도 체크표")
    write("20_부록/03_출력용_활동지.md", APPENDIX_SHEETS, 1, "부록 3 — 출력용 활동지 만들기")

    with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme(files))
    print(f"wikidocs: {len(files)} pages")
