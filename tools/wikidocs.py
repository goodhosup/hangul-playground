def unit_text(u):
    if u["unit"] in T:
        return T[u["unit"]]
    if u["stage"] == 2:
        return vowel_unit(u)
    if u["stage"] == 3:
        return consonant_unit(u)
    if u["stage"] == 5:
        return final_unit(u)
    raise KeyError(u["unit"])


def render_unit(u, prev_u, next_u):
    t = unit_text(u)
    links = "\n".join(f"- [{ACTS[a][1]} {ACTS[a][2]}]({href(a, u['unit'])})" for a in u["acts"])
    nav = []
    if prev_u:
        nav.append(f"◀ 이전 단원 **{prev_u['unit']} {prev_u['title']}**")
    if next_u:
        nav.append(f"다음 단원 ▶ **{next_u['unit']} {next_u['title']}**")
    tips = "\n".join("- " + x for x in t["tips"] if x)
    checks = "\n".join("- [ ] " + x for x in t["checks"])
    return f"""# {u['unit']} {u['title']}

> 🎯 **오늘의 목표**: {t['goal']}
> ⏱ **시간**: 10분 · 🧺 **준비물**: {t['prep']}

## 1. 복습 (1~2분)

{t['review']}

## 2. 오늘의 글자 (3분)

{t['today']}

## 3. 놀이 (3~4분)

### 놀이 A — {t['play_a'][0]}

{t['play_a'][1]}

### 놀이 B — {t['play_b'][0]}

{t['play_b'][1]}

## 4. 마무리 (1분)

- 스티커 1개를 붙여요.
- 오늘 읽은 것을 다시 말해 주세요. "오늘 이걸 해냈어! 대단하다!"

## ✅ 확인하기

{checks}

다 못 해도 괜찮아요. 다음 시간에 같은 단원을 한 번 더 하면 됩니다.

## 💡 부모 팁

{tips}

## 🔗 웹 놀이터

{links}

{' · '.join(nav)}
"""


