def decompose(ch):
    code = ord(ch) - 0xAC00
    return CHO[code // 588], JUNG[(code % 588) // 28], JONG[code % 28]


def compose(c, v, f=""):
    return chr(0xAC00 + (CHO.index(c) * 21 + JUNG.index(v)) * 28 + JONG.index(f))


def contains(syl, j):
    # 받침은 5부에서 배우므로 첫소리(초성)와 모음만 본다
    c, v, f = decompose(syl)
    return j in (c, v) or (j == "ㅏ" and v == "ㅘ") or (j == "ㅓ" and v == "ㅝ") or (j == "ㅣ" and v in "ㅚㅟㅢ")


def hl(word, j):
    out, run = [], ""
    for ch in word:
        if contains(ch, j):
            run += ch
        else:
            if run:
                out.append(f"**{run}**")
                run = ""
            out.append(ch)
    if run:
        out.append(f"**{run}**")
    return "".join(out)


